// The offline service worker, as source text. build.mjs stamps a version into it
// and writes dist/sw.js. The whole app is a few files (fonts are inlined). They are
// cached up front, but the network is asked first so that anyone online always gets
// the newest build (an audience member must never see a stale page); the cache
// answers only when the network fails or is slow. A new build gets a new cache
// name, and activating it removes the old ones.

export const CACHE_PREFIX = 'interactive-slides-';
export const SHELL_FILES = ['./', 'app/', 'app.js', 'app.css', 'site.css', 'tokens.css'];

export function serviceWorkerSource(version) {
  return `// Generated by build.mjs. Do not edit.
const CACHE = ${JSON.stringify(CACHE_PREFIX + version)};
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const SHELL = ${JSON.stringify(SHELL_FILES)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(SHELL.map((url) => new Request(url, { cache: 'reload' }))))
      .then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()));
});

const NETWORK_WAIT_MS = 4000;

// Ask the network, refresh the cached copy with what comes back, and fall back to
// the cache if the network fails or does not answer in time.
function networkFirst(request) {
  const scope = self.registration.scope;
  const appRoot = new URL('app/', scope);
  // Every address under /app/ is the same page; keep one copy of it.
  const isApp = request.mode === 'navigate' && new URL(request.url).pathname.startsWith(appRoot.pathname);
  const cached = () => caches.match(request, { ignoreSearch: true }).then((hit) => hit ?? (isApp ? caches.match(appRoot.href) : undefined));
  const fresh = fetch(request).then((response) => {
    if (response.ok && response.type === 'basic') {
      const copy = response.clone();
      caches.open(CACHE).then((cache) => cache.put(isApp ? appRoot.href : request, copy)).catch(() => {});
    }
    return response;
  });
  fresh.catch(() => {}); // a late failure after the cache already answered is not an error
  const timeout = new Promise((resolve) => setTimeout(() => resolve(null), NETWORK_WAIT_MS));
  return Promise.race([fresh, timeout])
    .then((response) => response ?? cached().then((hit) => hit ?? fresh))
    .catch(() => cached().then((hit) => hit ?? Response.error()));
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(networkFirst(request));
});
`;
}
